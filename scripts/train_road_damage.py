#!/usr/bin/env python3
"""
Custom Road Damage YOLO Training Pipeline
Trains or fine-tunes a YOLO model on the Road Damage Dataset (RDD2020 / RDD2022)
and exports the best checkpoint to backend/models/road_damage_best.pt.
"""

import sys
import os
import argparse
import shutil
from pathlib import Path

# Add backend directory to sys.path
backend_dir = Path(__file__).resolve().parent.parent / "backend"
sys.path.insert(0, str(backend_dir))

from ultralytics import YOLO
import torch
from app.core.config import settings
from app.core.logging import logger


def train_model(
    data_yaml: Path,
    epochs: int = 5,
    batch_size: int = 8,
    imgsz: int = 640,
    device: str = "cpu",
    base_weights: str = "yolov8n.pt"
) -> Path:
    print("=" * 75)
    print("CUSTOM ROAD DAMAGE YOLO MODEL TRAINING PIPELINE")
    print("=" * 75)
    print(f">> Dataset Config: {data_yaml}")
    print(f">> Base Weights:   {base_weights}")
    print(f">> Target Epochs:  {epochs}")
    print(f">> Batch Size:     {batch_size}")
    print(f">> Image Size:     {imgsz}x{imgsz}")
    print(f">> Compute Device: {device}")

    # Initialize model with base weights
    project_root = data_yaml.parent.parent.parent
    base_pt_path = project_root / "backend" / "models" / base_weights
    if not base_pt_path.exists():
        base_pt_path = Path(base_weights)

    # Ensure dataset YAML points to absolute path on this machine
    dataset_abs_path = (project_root / "data" / "road_damage").resolve().as_posix()
    yaml_content = f"""# Auto-generated by train_road_damage.py
path: {dataset_abs_path}
train: train/images
val: val/images

names:
  0: longitudinal_crack
  1: transverse_crack
  2: alligator_crack
  3: pothole
"""
    with open(data_yaml, "w", encoding="utf-8") as f:
        f.write(yaml_content)

    model = YOLO(str(base_pt_path))

    # Train model
    results = model.train(
        data=str(data_yaml),
        epochs=epochs,
        batch=batch_size,
        imgsz=imgsz,
        device=device,
        project=str(project_root / "runs" / "road_damage"),
        name="rdd_train",
        exist_ok=True,
        verbose=True,
        save=True,
        mosaic=1.0,  # Data augmentation
        hsv_h=0.015,
        hsv_s=0.7,
        hsv_v=0.4
    )

    # Locate best weights
    best_weights_path = project_root / "runs" / "road_damage" / "rdd_train" / "weights" / "best.pt"
    if not best_weights_path.exists():
        best_weights_path = project_root / "runs" / "road_damage" / "rdd_train" / "weights" / "last.pt"

    target_weights_path = project_root / "backend" / "models" / "road_damage_best.pt"
    target_weights_path.parent.mkdir(parents=True, exist_ok=True)

    if best_weights_path.exists():
        shutil.copy(best_weights_path, target_weights_path)
        print(f"\n[SUCCESS] Custom Road Damage weights exported to: {target_weights_path}")
    else:
        print("\n[WARNING] Could not locate output best.pt, copying base weights as fallback.")
        shutil.copy(base_pt_path, target_weights_path)

    return target_weights_path


def main():
    parser = argparse.ArgumentParser(description="Train Custom Road Damage YOLO Model")
    parser.add_argument("--epochs", type=int, default=3, help="Number of training epochs")
    parser.add_argument("--batch", type=int, default=8, help="Batch size")
    parser.add_argument("--imgsz", type=int, default=640, help="Image resolution")
    parser.add_argument("--device", type=str, default="cpu", help="Device (cpu, cuda:0)")
    parser.add_argument("--data", type=str, default="backend/models/road_damage.yaml", help="Path to data YAML")
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parent.parent
    data_yaml = project_root / args.data

    device = "cuda:0" if args.device == "cuda" and torch.cuda.is_available() else "cpu"

    train_model(
        data_yaml=data_yaml,
        epochs=args.epochs,
        batch_size=args.batch,
        imgsz=args.imgsz,
        device=device
    )


if __name__ == "__main__":
    main()
